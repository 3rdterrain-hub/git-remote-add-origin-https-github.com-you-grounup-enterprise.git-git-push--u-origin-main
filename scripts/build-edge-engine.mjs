/**
 * Put the deterministic engine where the Edge runtime can reach it.
 *
 * The engine is the single authoritative source of estimating arithmetic, and
 * since migration 0058 it is also the only thing permitted to write a price.
 * That means it has to run somewhere the browser cannot reach or forge — an
 * Edge Function holding the service role — which raises a plain packaging
 * question: how does Deno get the code?
 *
 * Not by relative import out of `supabase/functions/`. That happens to work
 * with today's bundler and is one CLI release away from not working, and a
 * deploy that silently ships without the engine would leave the one function
 * that prices estimates unable to price estimates.
 *
 * So the compiled engine is generated into `_shared/engine/` and committed. It
 * is a build artifact, not hand-written code, and `--check` fails the build if
 * it has drifted from `packages/engine/src` — the same generated-artifact and
 * drift-check pattern the OpenAPI document, the traceability register and the
 * schema counts already use. The engine has no dependencies, so the compiled
 * output is plain ESM with no imports to resolve and nothing to vendor.
 *
 *   node scripts/build-edge-engine.mjs           regenerate
 *   node scripts/build-edge-engine.mjs --check    fail if stale
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, rmSync, mkdtempSync, existsSync, cpSync, writeFileSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'packages/engine/src');
const OUT = join(ROOT, 'supabase/functions/_shared/engine');
const check = process.argv.includes('--check');

/** Every emitted file, hashed, so drift is a single comparison. */
function fingerprint(dir) {
  if (!existsSync(dir)) return null;
  const files = [];
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name !== 'FINGERPRINT') files.push(p);
    }
  };
  walk(dir);
  const h = createHash('sha256');
  for (const f of files) {
    h.update(relative(dir, f));
    h.update(readFileSync(f));
  }
  return h.digest('hex');
}

const staging = mkdtempSync(join(tmpdir(), 'grounup-engine-'));
try {
  execFileSync('npx', ['tsc', '-p', join(ROOT, 'packages/engine/tsconfig.build.json'),
    // Declarations are emitted on purpose: the Edge Function that maps database
    // rows into engine inputs is typechecked against this copy, so a field
    // renamed in the engine breaks the build rather than the deploy.
    '--outDir', staging, '--declaration', 'true', '--declarationMap', 'false',
    '--sourceMap', 'false'],
    { cwd: ROOT, stdio: 'inherit' });

  const built = fingerprint(staging);
  const current = fingerprint(OUT);

  if (check) {
    if (built !== current) {
      console.error('The Edge copy of the estimating engine is stale.\n');
      console.error(`  packages/engine/src compiles to ${built}`);
      console.error(`  supabase/functions/_shared/engine is ${current ?? 'missing'}\n`);
      console.error('Run `npm run engine:edge` and commit the result. The Edge Function that');
      console.error('prices estimates loads this copy; a stale one prices with old arithmetic.');
      process.exit(1);
    }
    console.log(`Edge engine copy matches packages/engine/src (${built.slice(0, 12)}).`);
  } else {
    rmSync(OUT, { recursive: true, force: true });
    cpSync(staging, OUT, { recursive: true });
    writeFileSync(join(OUT, 'FINGERPRINT'),
      `${built}\n\nGenerated by scripts/build-edge-engine.mjs from packages/engine/src.\n` +
      'Do not edit by hand. Run `npm run engine:edge` after changing the engine.\n');
    const count = readdirSync(OUT).length;
    console.log(`Edge engine copy regenerated: ${count} files, fingerprint ${built.slice(0, 12)}.`);
  }
} finally {
  rmSync(staging, { recursive: true, force: true });
}
